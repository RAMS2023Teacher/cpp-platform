// Builds the files that go into Google Apps Script: apps-script/{Code.gs, Lessons.gs, Index.html, appsscript.json}.
// Apps Script serves a single page, so all CSS and JS is inlined into Index.html.
const fs = require('fs');
const path = require('path');

function parseCsv(text) {
  const rows = [[]]; let cell = '', quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) { if (c === '"' && text[i + 1] === '"') { cell += '"'; i++; } else if (c === '"') quoted = false; else cell += c; }
    else if (c === '"') quoted = true;
    else if (c === ',') { rows.at(-1).push(cell); cell = ''; }
    else if (c === '\n') { rows.at(-1).push(cell.replace(/\r$/, '')); cell = ''; rows.push([]); }
    else cell += c;
  }
  if (cell) rows.at(-1).push(cell);
  return rows.filter(r => r.length >= 5);
}

function standardsMap(lessons, standards, plans) {
  const list = c => c.map(x => x.replace('6-8.', '')).join(', ') || '—';
  const uses = code => lessons.filter(l => [...l.standards.anchor, ...l.standards.supporting].includes(code));
  const covered = ids => { const inPlan = lessons.filter(l => !ids || ids.includes(l.id)); return { anchor: new Set(inPlan.flatMap(l => l.standards.anchor)), any: new Set(inPlan.flatMap(l => [...l.standards.anchor, ...l.standards.supporting])) }; };
  const row = (name, ids) => { const c = covered(ids); return `| ${name} | ${c.anchor.size} | ${c.any.size} |`; };
  const addressed = standards.filter(s => uses(s.code).length), missing = standards.filter(s => !uses(s.code).length);
  const cell = t => t.replace(/\|/g, '\\|');
  return `<!-- Generated by tools/build-gas.js from lessons/supports.js. Edit that file, not this one. -->
# RoboCode Academy: MA DLCS Standards Map

Standards are the Massachusetts Digital Literacy and Computer Science (2016) grades 6-8 standards, quoted verbatim. Codes in the tables omit the \`6-8.\` prefix.

- **Anchor:** taught and assessed in the lesson through its code challenge, exit ticket, or build.
- **Supporting:** practiced in the lesson, but not the main thing assessed.

## Coverage by term

| Term | Standards assessed (anchor) | Standards addressed (anchor or supporting) |
|---|---|---|
${row(`${plans[10].length} lessons`, plans[10])}
${row(`${plans[12].length} lessons`, plans[12])}
${row(`${plans[15].length} lessons`, plans[15])}
${row(`Full course (${lessons.length} lessons)`, null)}

The state list has ${standards.length} grades 6-8 standards.

## By lesson

| # | Lesson | In terms | Anchor | Supporting |
|---|---|---|---|---|
${lessons.map(l => `| ${l.order} | ${cell(l.title)} | ${[10, 12, 15].filter(n => plans[n].includes(l.id)).map(n => plans[n].length).join(", ") || "Go Further"} | ${list(l.standards.anchor)} | ${list(l.standards.supporting)} |`).join('\n')}

## By standard

| Code | Standard | Anchor lessons | Supporting lessons |
|---|---|---|---|
${addressed.map(s => `| ${s.code.replace('6-8.', '')} | ${cell(s.text)} | ${lessons.filter(l => l.standards.anchor.includes(s.code)).map(l => l.order).join(', ') || '—'} | ${lessons.filter(l => l.standards.supporting.includes(s.code)).map(l => l.order).join(', ') || '—'} |`).join('\n')}

## Not addressed by this course

These are outside a robotics and programming course and would need to be taught elsewhere.

| Code | Standard |
|---|---|
${missing.map(s => `| ${s.code.replace('6-8.', '')} | ${cell(s.text)} |`).join('\n')}
`;
}

const root = path.join(__dirname, '..');
const out = path.join(root, 'apps-script');
const read = p => fs.readFileSync(path.join(root, p), 'utf8');
fs.mkdirSync(out, { recursive: true });

fs.copyFileSync(path.join(root, 'gas/Code.gs'), path.join(out, 'Code.gs'));
fs.copyFileSync(path.join(root, 'gas/appsscript.json'), path.join(out, 'appsscript.json'));

const lessons = fs.readdirSync(path.join(root, 'lessons'))
  .filter(f => /^unit\d+\.js$/.test(f))
  .flatMap(f => require(path.join(root, 'lessons', f)))
  .sort((a, b) => a.order - b.order);
const { plans, prereqs, photos, events } = require(path.join(root, 'lessons/plans.js'));
for (const [id, ev] of Object.entries(events)) for (const [n, list] of Object.entries(plans)) if (!list.includes(ev.after)) throw new Error(`Event ${id} follows ${ev.after}, which is not in the ${n}-lesson term`);
// Standards: verbatim from the state list, and every lesson must be mapped.
const STANDARDS = parseCsv(read('lessons/dlcs_standards.csv')).slice(1).map(([grade, strand, topic, code, text]) => ({ strand, topic, code, text: text.replace(/\s+/g, ' ').trim() }));
const codes = new Set(STANDARDS.map(s => s.code));
const supports = require(path.join(root, 'lessons/supports.js'));
for (const l of lessons) {
  const s = supports[l.id];
  if (!s) throw new Error(`lessons/supports.js has no entry for ${l.id}`);
  if (!s.standards.anchor.length) throw new Error(`${l.id} has no anchor standard`);
  for (const c of [...s.standards.anchor, ...s.standards.supporting]) if (!codes.has(c)) throw new Error(`${l.id} cites an unknown standard: ${c}`);
  if (!s.visual.alt) throw new Error(`${l.id}: its diagram needs alt text`);
  const { standards, ...rest } = s;
  l.standards = standards; l.supports = rest;
}
// "Where to look" screenshots: <figure class="shot" data-shot="NAME"><figcaption>…</figcaption></figure> in lesson HTML
// becomes the picture in shots/NAME.webp (or .png / .jpg), embedded in Lessons.gs, or a "coming soon" box until it exists.
const shotDir = path.join(root, 'shots'), shotTypes = { webp: 'image/webp', png: 'image/png', jpg: 'image/jpeg' };
const shotsUsed = new Set(), shotsMissing = new Set();
let shotBytes = 0;
const withShots = html => html.replace(/<figure class="shot" data-shot="([\w-]+)">\s*<figcaption>([\s\S]*?)<\/figcaption>\s*<\/figure>/g, (_, name, caption) => {
  shotsUsed.add(name);
  const ext = Object.keys(shotTypes).find(e => fs.existsSync(path.join(shotDir, `${name}.${e}`)));
  const alt = caption.replace(/<[^>]+>/g, '').replace(/"/g, '&quot;');
  if (!ext) { shotsMissing.add(name); return `<figure class="shot"><div class="shot-missing">📷 Picture coming soon: ${caption}</div></figure>`; }
  const bytes = fs.readFileSync(path.join(shotDir, `${name}.${ext}`));
  shotBytes += bytes.length;
  return `<figure class="shot"><img src="data:${shotTypes[ext]};base64,${bytes.toString('base64')}" alt="${alt}" loading="lazy"><figcaption>${caption}</figcaption></figure>`;
});
for (const l of lessons) {
  for (const sec of l.sections || []) sec.html = withShots(sec.html);
  if (l.challenge) l.challenge.prompt = withShots(l.challenge.prompt);
}
if (shotsMissing.size) console.log(`Screenshots still to add in shots/ (see docs/SCREENSHOTS.md): ${[...shotsMissing].join(', ')}`);
if (shotBytes > 400 * 1024) throw new Error(`Screenshots add ${Math.round(shotBytes / 1024)} KB; keep them under 400 KB in total (Google refuses to save very large projects). Use smaller WebP files.`);

const traces = require(path.join(root, 'lessons/traces.js'));
let turn = 0;
for (const l of lessons) {
  if (l.challenge && !traces[l.id]) throw new Error(`${l.id} needs a code-reading question in lessons/traces.js`);
  if (traces[l.id]) {
    const [code, out, wrong] = traces[l.id];
    l.quiz.push({ q: 'What does this code print?', code, choices: [out, ...wrong], answer: 0, explain: `Follow each line in order. This code prints ${out}.` });
  }
  // Rotate where the right answer sits, so its position gives nothing away.
  for (const q of l.quiz) {
    if (q.choices.includes('A') && q.choices.includes('B') && !q.code) continue; // these name programs A and B, so they stay in order
    const target = turn++ % q.choices.length, right = q.choices[q.answer], others = q.choices.filter((_, i) => i !== q.answer);
    others.splice(target, 0, right);
    q.choices = others; q.answer = target;
  }
}
const known = new Set(lessons.map(l => l.id));
for (const id of [...Object.values(plans).flat(), ...Object.keys(prereqs), ...Object.values(prereqs).flat(), ...Object.keys(photos)]) if (!known.has(id)) throw new Error(`lessons/plans.js names an unknown lesson: ${id}`);
fs.writeFileSync(path.join(out, 'Lessons.gs'), `// Generated by tools/build-gas.js from lessons/. Edit those files, not this one.\nvar LESSONS = ${JSON.stringify(lessons)};\nvar PLANS = ${JSON.stringify(plans)};\nvar PREREQS = ${JSON.stringify(prereqs)};\nvar STANDARDS = ${JSON.stringify(STANDARDS)};\nvar PHOTO_LESSONS = ${JSON.stringify(photos)};\nvar EVENTS = ${JSON.stringify(events)};\n`);
fs.writeFileSync(path.join(root, 'docs/STANDARDS_MAP.md'), standardsMap(lessons, STANDARDS, plans));

// Apps Script's HtmlService mangles regular expression literals that contain // or /* or */,
// or an unescaped / inside [...], which broke the simulator on the live site. Refuse to build with them.
function checkRegexps(file) {
  const acorn = require('acorn'), src = read(file), bad = [];
  acorn.parse(src, { ecmaVersion: 'latest', locations: true, onToken: t => {
    if (t.type.label !== 'regexp') return;
    const raw = src.slice(t.start, t.end); let inClass = false, slashInClass = false;
    for (let i = 0; i < t.value.pattern.length; i++) {
      const ch = t.value.pattern[i];
      if (ch === '\\') i++; else if (ch === '[') inClass = true; else if (ch === ']') inClass = false; else if (ch === '/' && inClass) slashInClass = true;
    }
    if (slashInClass || /\/\*|\*\/|\/\//.test(raw.slice(1))) bad.push(`${file}:${t.loc.start.line}  ${raw}`);
  } });
  if (bad.length) throw new Error('These regular expressions break on Apps Script. Rewrite them without //, /* or */ and escape / inside [...] (for example [\\/] or \\s{0,}):\n  ' + bad.join('\n  '));
}
for (const f of fs.readdirSync(path.join(root, 'public/js'))) if (f.endsWith('.js')) checkRegexps(`public/js/${f}`);

const source = url => url.startsWith('/vendor/codemirror/') ? `node_modules/codemirror/${url.slice('/vendor/codemirror/'.length)}` : `public${url}`;
const html = read('public/index.html')
  .replace(/<link rel="stylesheet" href="(\/[^"]+)">/g, (_, url) => `<style>\n${read(source(url))}\n</style>`)
  .replace(/<script src="(\/[^"]+)"><\/script>/g, (_, url) => `<script>\n${read(source(url)).replace(/<\/script/gi, '<\\/script')}\n;(window.__loaded = window.__loaded || []).push(${JSON.stringify(url.split('/').pop())});\n</script>`);
fs.writeFileSync(path.join(out, 'Index.html'), html);

for (const f of fs.readdirSync(out)) console.log(`${f.padEnd(18)} ${Math.round(fs.statSync(path.join(out, f)).size / 1024)} KB`);
