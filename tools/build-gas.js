// Builds the files that go into Google Apps Script: apps-script/{Code.gs, Lessons.gs, Index.html, appsscript.json}.
// Apps Script serves a single page, so all CSS and JS is inlined into Index.html.
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const out = path.join(root, 'apps-script');
const read = p => fs.readFileSync(path.join(root, p), 'utf8');
fs.mkdirSync(out, { recursive: true });

fs.copyFileSync(path.join(root, 'gas/Code.gs'), path.join(out, 'Code.gs'));
fs.copyFileSync(path.join(root, 'gas/appsscript.json'), path.join(out, 'appsscript.json'));

const lessons = fs.readdirSync(path.join(root, 'lessons'))
  .filter(f => /^unit\d+\.js$/.test(f))
  .flatMap(f => require(path.join(root, 'lessons', f)))
  .sort((a, b) => a.order - b.order);
fs.writeFileSync(path.join(out, 'Lessons.gs'), `// Generated by tools/build-gas.js from lessons/. Edit those files, not this one.\nvar LESSONS = ${JSON.stringify(lessons)};\n`);

const source = url => url.startsWith('/vendor/codemirror/') ? `node_modules/codemirror/${url.slice('/vendor/codemirror/'.length)}` : `public${url}`;
const html = read('public/index.html')
  .replace(/<link rel="stylesheet" href="(\/[^"]+)">/g, (_, url) => `<style>\n${read(source(url))}\n</style>`)
  .replace(/<script src="(\/[^"]+)"><\/script>/g, (_, url) => `<script>\n${read(source(url)).replace(/<\/script/gi, '<\\/script')}\n</script>`);
fs.writeFileSync(path.join(out, 'Index.html'), html);

for (const f of fs.readdirSync(out)) console.log(`${f.padEnd(18)} ${Math.round(fs.statSync(path.join(out, f)).size / 1024)} KB`);
